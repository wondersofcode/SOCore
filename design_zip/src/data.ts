export const alerts: Alert[] = [...baseAlerts, ...queueAlerts].map(a => {
  const riskScore = computeRisk(a)
  // The playbook threshold: only alerts above 70 get a proposed response action.
  const needsAction = riskScore > 70 && a.status !== 'Resolved'
  const proposedAction: ProposedAction | null = needsAction
    ? {
        action: actionByAttack[a.attackType] ?? 'Block source IP at the perimeter firewall',
        target: a.sourceIP,
        playbook: `PB-${a.attackType.toLowerCase().replace(/[^a-z]+/g, '-')}`,
        dryRun: true,
      }
    : null
  return {
    ...a,
    riskScore,
    aiExplanation: explain(a, riskScore),
    aiConfidence: Math.min(99, 60 + Math.round(Math.max(a.vtScore, a.abuseScore) * 0.3)),
    proposedAction,
    approvalStatus: proposedAction ? (decided[a.id] ?? 'Pending') : 'None',
    sources: buildSources(a),
  }
})

