function explain(a: AlertSeed, risk: number): string {
  const known = handwrittenExplanations[a.id]
  if (known) return known
  const rep = Math.max(a.vtScore, a.abuseScore)
  const origin = a.country === 'INTERNAL'
    ? 'The source is an internal address, so reputation feeds add nothing and the behaviour itself carries the signal.'
    : rep >= 70
      ? `The source address is flagged by threat intelligence with a confidence of ${rep}, which raises the weight of this detection considerably.`
      : rep > 0
        ? `Threat intelligence returns a low confidence of ${rep} for this address, so the detection rests mainly on the observed behaviour.`
        : 'Threat intelligence has no record of this address, so the detection rests entirely on the observed behaviour.'
  return `Activity matching ${a.mitreName} (${a.mitreId}) was observed from ${a.sourceIP}. ${origin} The correlation engine scored this at ${risk}, which places it ${risk > 70 ? 'above' : 'below'} the automatic response threshold.`
}

function buildSources(a: AlertSeed): EnrichmentSource[] {
  const rep = Math.max(a.vtScore, a.abuseScore)
  const internal = a.country === 'INTERNAL'
  const enriched = !!a.enrichedAt
  return [
    { name: 'Wazuh', status: 'hit', detail: `Rule matched on ${a.mitreId}`, at: a.detectedAt },
    {
      name: 'MISP',
      status: internal ? 'skipped' : rep >= 70 ? 'hit' : enriched ? 'clean' : 'pending',
      detail: internal
        ? 'Internal address — not submitted to the IOC database'
        : rep >= 70
          ? 'Address appears in an active IOC event'
          : enriched ? 'No matching IOC event' : 'Lookup queued',
      at: a.enrichedAt || '—',
    },
    {
      name: 'Cortex',
      status: enriched ? 'hit' : 'pending',
      detail: enriched ? 'Analyzers completed' : 'Analyzers not yet run',
      at: a.enrichedAt || '—',
    },
    {
      name: 'VirusTotal',
      status: enriched ? (a.vtScore >= 40 ? 'hit' : 'clean') : 'pending',
      detail: enriched ? `Malicious score ${a.vtScore}/100` : 'Awaiting analyzer run',
      at: a.enrichedAt || '—',
    },
    {
      name: 'AbuseIPDB',
      status: enriched ? (a.abuseScore >= 40 ? 'hit' : 'clean') : 'pending',
      detail: enriched ? `Abuse confidence ${a.abuseScore}%` : 'Awaiting analyzer run',
      at: a.enrichedAt || '—',
    },
    {
      name: 'TheHive',
      status: a.status === 'Responding' || a.status === 'Resolved' ? 'hit' : 'skipped',
      detail: a.status === 'Responding' || a.status === 'Resolved'
        ? 'Case opened from this alert'
        : 'No case opened yet',
      at: a.respondedAt || '—',
    },
  ]
}

