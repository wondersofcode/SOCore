export type Severity = 'Critical' | 'High' | 'Medium' | 'Low' | 'Informational'
export type AlertStatus = 'New' | 'Enriching' | 'Responding' | 'Resolved'
export type CaseStatus = 'Open' | 'Investigating' | 'Contained' | 'Closed'
export type SimStatus = 'Planned' | 'Scripted' | 'Tested' | 'Detected'
export type ApprovalStatus = 'None' | 'Pending' | 'Approved' | 'Rejected'
export type SourceStatus = 'hit' | 'clean' | 'pending' | 'skipped'
export type UserRole = 'l1_analyst' | 'l2_analyst' | 'admin'
export type UserStatus = 'pending' | 'approved' | 'rejected'

/** A `profiles` row, as the admin panel and Settings page see it. */
export interface AdminUser {
  id: string
  email: string
  displayName: string
  firstName: string
  lastName: string
  avatarUrl: string
  role: UserRole
  status: UserStatus
  themePreference: 'dark' | 'light'
  createdAt: string
}

/** Where a piece of enrichment came from — mirrors the real SOCore pipeline. */
export interface EnrichmentSource {
  name: 'Wazuh' | 'MISP' | 'Cortex' | 'VirusTotal' | 'AbuseIPDB' | 'TheHive'
  status: SourceStatus
  detail: string
  at: string
}

/** A response action the automation proposes but will not run without a human. */
export interface ProposedAction {
  action: string
  target: string
  playbook: string
  dryRun: boolean
}

export interface Alert {
  id: string
  timestamp: string
  severity: Severity
  sourceIP: string
  attackType: string
  mitreId: string
  mitreName: string
  status: AlertStatus
  analyst: string
  raw: string
  vtScore: number
  abuseScore: number
  country: string
  asn: string
  detectedAt: string
  enrichedAt: string
  respondedAt: string
  /** 0–100 score produced by the correlation engine. Drives playbook thresholds. */
  riskScore: number
  /** Plain-language reasoning generated by the AI layer. */
  aiExplanation: string
  aiConfidence: number
  /** Populated when risk_score crosses the playbook threshold. */
  proposedAction: ProposedAction | null
  approvalStatus: ApprovalStatus
  sources: EnrichmentSource[]
  /** The raw Wazuh event this alert was scored from, if any (seed alerts have none). */
  sourceEventId?: string | null
}

/** A raw, unscored Wazuh event — recorded independently of whatever Alert it becomes. */
export interface WazuhRawEvent {
  id: string
  timestamp: string
  sourceIP: string
  ruleId: string
  ruleLevel: number
  ruleDescription: string
  raw: string
  agentId: string
  agentName: string
  /** Set once the correlation engine turns this event into an Alert. Not every event is. */
  alertId: string | null
}

/** Alert fields authored by hand; the rest are derived below. */
type AlertSeed = Omit<Alert, 'riskScore' | 'aiExplanation' | 'aiConfidence' | 'proposedAction' | 'approvalStatus' | 'sources'>

