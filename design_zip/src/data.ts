// ── Correlation + AI layer ──────────────────────────────────────────────────
// In production these fields arrive from the backend: the correlation engine
// computes risk_score, the AI layer writes ai_explanation, and the SOAR
// playbook attaches a proposed action once the score crosses its threshold.

const severityWeight: Record<Severity, number> = {
  Critical: 46, High: 33, Medium: 20, Low: 10, Informational: 4,
}

/** Same weighting the backend correlation engine applies. */
function computeRisk(a: AlertSeed): number {
  const reputation = Math.max(a.vtScore, a.abuseScore) * 0.42
  const external = a.country === 'INTERNAL' ? 0 : 8
  const unresolved = a.status === 'Resolved' ? -14 : 0
  return Math.max(0, Math.min(100, Math.round(severityWeight[a.severity] + reputation + external + unresolved)))
}

